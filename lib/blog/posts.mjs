function isVisible(post, preview) {
  if (preview) return true;
  if (post.status === "published") return true;
  return false;
}

function normalizeLanguage(language) {
  return language === "en" || language === "tr" ? language : "ar";
}

function getPostCopy(post, language) {
  const normalizedLanguage = normalizeLanguage(language);
  const content = post.contentByLanguage[normalizedLanguage] || post.contentByLanguage.ar;
  return {
    ...content,
    title: content.title || post.contentByLanguage.ar.title,
    excerpt: content.excerpt || post.contentByLanguage.ar.excerpt,
    content: content.content || post.contentByLanguage.ar.content,
  };
}

function getVisiblePosts(language, preview) {
  const normalizedLanguage = normalizeLanguage(language);
  return posts
    .filter((post) => isVisible(post, preview))
    .map((post) => ({
      ...post,
      copy: getPostCopy(post, normalizedLanguage),
    }))
    .sort((left, right) => {
      const leftDate = left.publishedAt || left.scheduledAt || "1970-01-01T00:00:00.000Z";
      const rightDate = right.publishedAt || right.scheduledAt || "1970-01-01T00:00:00.000Z";
      return new Date(rightDate) - new Date(leftDate);
    });
}

export function getBlogPosts({ language = "ar", page = 1, perPage = 6, search = "", category = "", tag = "", preview = false } = {}) {
  const normalizedLanguage = normalizeLanguage(language);
  const visiblePosts = getVisiblePosts(normalizedLanguage, preview)
    .filter((post) => {
      if (category && post.category !== category) return false;
      if (tag && !post.tags.includes(tag)) return false;
      if (!search.trim()) return true;
      const haystack = `${post.copy.title} ${post.copy.excerpt} ${post.copy.content} ${post.tags.join(" ")} ${post.category}`.toLowerCase();
      return haystack.includes(search.trim().toLowerCase());
    });

  const total = visiblePosts.length;
  const totalPages = Math.max(1, Math.ceil(total / perPage));
  const safePage = Math.min(Math.max(page, 1), totalPages);
  const start = (safePage - 1) * perPage;
  return {
    posts: visiblePosts.slice(start, start + perPage),
    page: safePage,
    perPage,
    total,
    totalPages,
    language: normalizedLanguage,
    labels: languageLabels[normalizedLanguage],
  };
}

export function getBlogPostBySlug(slug, { language = "ar", preview = false } = {}) {
  const normalizedLanguage = normalizeLanguage(language);
  const post = posts.find((item) => item.slug === slug);
  if (!post) return null;
  if (!isVisible(post, preview)) return null;
  return {
    ...post,
    copy: getPostCopy(post, normalizedLanguage),
  };
}

export function getBlogCategories(language = "ar") {
  const normalizedLanguage = normalizeLanguage(language);
  return posts.reduce((accumulator, post) => {
    if (!accumulator[post.category]) {
      accumulator[post.category] = { slug: post.category, label: categoryNames[normalizedLanguage][post.category] || post.category };
    }
    return accumulator;
  }, {});
}

export function getBlogTags(language = "ar") {
  void language;
  return posts.reduce((accumulator, post) => {
    post.tags.forEach((tag) => {
      if (!accumulator[tag]) {
        accumulator[tag] = { slug: tag, label: tag };
      }
    });
    return accumulator;
  }, {});
}

export function getRelatedBlogPosts(post, { language = "ar", preview = false, limit = 3 } = {}) {
  const normalizedLanguage = normalizeLanguage(language);
  return getVisiblePosts(normalizedLanguage, preview)
    .filter((item) => item.id !== post.id && item.category === post.category)
    .slice(0, limit);
}

export function getBlogFeed(language = "ar") {
  return getVisiblePosts(normalizeLanguage(language), true).slice(0, 10);
}