-- New exposed tables always use RLS.
do $$
declare t text;
begin
  foreach t in array array[
    'tenant_admin_audit','portal_files','portal_notification_preferences','marketplace_carts','marketplace_cart_items',
    'payment_transactions','payment_webhook_events','payment_refunds','marketplace_disputes','whatsapp_templates',
    'communication_consents','ai_sessions','ai_messages','ai_knowledge_documents','provider_health_checks'
  ] loop
    execute format('alter table public.%I enable row level security',t);
  end loop;
end $$;

create policy "tenant admins read tenant audit" on public.tenant_admin_audit for select to authenticated
using (public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin']));
create policy "owners read portal files" on public.portal_files for select to authenticated
using (owner_user_id=(select auth.uid()) or public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin','employee']));
create policy "owners manage notification preferences" on public.portal_notification_preferences for all to authenticated
using (user_id=(select auth.uid())) with check (user_id=(select auth.uid()));
create policy "owners manage active cart" on public.marketplace_carts for all to authenticated
using (user_id=(select auth.uid())) with check (user_id=(select auth.uid()) and public.current_user_has_tenant_role(tenant_id,array['client','creator','partner','employee','tenant_admin','super_admin']));
create policy "owners read cart items" on public.marketplace_cart_items for select to authenticated
using (exists(select 1 from public.marketplace_carts c where c.id=cart_id and c.user_id=(select auth.uid())));
create policy "users manage communication consent" on public.communication_consents for all to authenticated
using (user_id=(select auth.uid())) with check (user_id=(select auth.uid()));
create policy "users read own ai sessions" on public.ai_sessions for select to authenticated
using (user_id=(select auth.uid()) or public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin','employee']));
create policy "users read own ai messages" on public.ai_messages for select to authenticated
using (exists(select 1 from public.ai_sessions s where s.id=session_id and (s.user_id=(select auth.uid()) or public.current_user_has_tenant_role(s.tenant_id,array['super_admin','tenant_admin','employee']))));
create policy "tenant staff read provider health" on public.provider_health_checks for select to authenticated
using (public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin','employee']));
create policy "users read own disputes" on public.marketplace_disputes for select to authenticated
using (opened_by=(select auth.uid()) or public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin','employee','partner']));

