insert into public.tenant_feature_flags(tenant_id,feature_key,enabled,configuration)
select id,feature_key,enabled,'{}'::jsonb from public.tenants cross join (values
 ('creator_portal',true),('client_portal',true),('employee_portal',true),('partner_portal',true),
 ('tasks',true),('sla',true),('workflows',true),('marketplace',true),('privacy_center',true),('pwa',true),
 ('push',false),('whatsapp',false),('ai_provider',false),('payments',false),('mobile_wrapper',false)
) as f(feature_key,enabled)
on conflict (tenant_id,feature_key) do nothing;

