-- Additive-only. No existing rows are deleted or rewritten outside tenant-safe backfill.

create table if not exists public.tenant_admin_audit (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  actor_id uuid references auth.users(id),
  action text not null,
  entity_type text not null,
  entity_id text,
  before_data jsonb,
  after_data jsonb,
  correlation_id uuid not null default gen_random_uuid(),
  created_at timestamptz not null default now()
);

create table if not exists public.portal_files (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  media_id bigint,
  category text not null default 'document',
  visibility text not null default 'owner' check (visibility in ('owner','assigned_staff','tenant_admin')),
  status text not null default 'active' check (status in ('active','archived','deleted')),
  created_at timestamptz not null default now()
);

create table if not exists public.portal_notification_preferences (
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  channel text not null check (channel in ('in_app','email','push','whatsapp')),
  event_key text not null,
  enabled boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (tenant_id,user_id,channel,event_key)
);

create table if not exists public.marketplace_carts (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'active' check (status in ('active','converted','abandoned')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id,user_id,status)
);
create table if not exists public.marketplace_cart_items (
  cart_id uuid not null references public.marketplace_carts(id) on delete cascade,
  listing_id uuid not null references public.marketplace_listings(id) on delete cascade,
  quantity integer not null default 1 check (quantity > 0),
  created_at timestamptz not null default now(),
  primary key (cart_id,listing_id)
);

create table if not exists public.payment_transactions (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  intent_id uuid references public.payment_intents(id) on delete set null,
  provider_event_id text,
  transaction_type text not null check (transaction_type in ('authorize','capture','payment','refund','void','failure')),
  amount numeric(14,2) not null,
  currency text not null,
  status text not null,
  raw_reference jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (tenant_id,provider_event_id)
);
create table if not exists public.payment_webhook_events (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  provider_key text not null,
  event_id text not null,
  signature_valid boolean not null default false,
  payload_digest text not null,
  processing_status text not null default 'received' check (processing_status in ('received','processed','ignored','failed')),
  received_at timestamptz not null default now(),
  processed_at timestamptz,
  unique (tenant_id,provider_key,event_id)
);
create table if not exists public.payment_refunds (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  order_id uuid not null references public.marketplace_orders(id) on delete cascade,
  transaction_id uuid references public.payment_transactions(id),
  amount numeric(14,2) not null check (amount > 0),
  reason text,
  status text not null default 'requested' check (status in ('requested','approved','processing','completed','rejected','failed')),
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);
create table if not exists public.marketplace_disputes (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  order_id uuid not null references public.marketplace_orders(id) on delete cascade,
  opened_by uuid references auth.users(id),
  reason text not null,
  status text not null default 'open' check (status in ('open','under_review','resolved','rejected','closed')),
  resolution text,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table if not exists public.whatsapp_templates (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  template_key text not null,
  locale text not null check (locale in ('ar','en','tr')),
  provider_template_name text,
  body text not null,
  variables jsonb not null default '[]'::jsonb,
  status text not null default 'draft' check (status in ('draft','approved','disabled')),
  created_at timestamptz not null default now(),
  unique (tenant_id,template_key,locale)
);
create table if not exists public.communication_consents (
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  channel text not null check (channel in ('email','push','whatsapp','marketing')),
  opted_in boolean not null default false,
  source text,
  recorded_at timestamptz not null default now(),
  withdrawn_at timestamptz,
  primary key (tenant_id,user_id,channel)
);

create table if not exists public.ai_sessions (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  user_id uuid references auth.users(id) on delete cascade,
  surface text not null check (surface in ('public','creator','client','employee','partner','admin')),
