create table if not exists public.commerce_events (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  order_id uuid references public.marketplace_orders(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  idempotency_key text,
  created_at timestamptz not null default now(),
  unique (tenant_id,idempotency_key)
);

create table if not exists public.marketplace_dispute_messages (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  dispute_id uuid not null references public.marketplace_disputes(id) on delete cascade,
  author_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 5000),
  created_at timestamptz not null default now()
);

alter table public.payment_refunds add column if not exists reviewed_by uuid references auth.users(id) on delete set null;
alter table public.payment_refunds add column if not exists reviewed_at timestamptz;
alter table public.payment_refunds add column if not exists decision_note text;
alter table public.marketplace_disputes add column if not exists closed_by uuid references auth.users(id) on delete set null;
alter table public.marketplace_disputes add column if not exists updated_at timestamptz not null default now();
alter table public.workflow_runs add column if not exists last_error_code text;
alter table public.workflow_runs add column if not exists current_step integer not null default 0;
alter table public.sla_events add column if not exists idempotency_key text;
create unique index if not exists sla_events_tenant_idempotency_uidx on public.sla_events(tenant_id,idempotency_key) where idempotency_key is not null;

alter table public.commerce_events enable row level security;
alter table public.marketplace_dispute_messages enable row level security;

create policy "commerce participants read events" on public.commerce_events for select to authenticated
using (
  actor_id=(select auth.uid())
  or exists(select 1 from public.marketplace_orders o where o.id=order_id and o.client_user_id=(select auth.uid()))
  or public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin','employee','partner'])
);
create policy "dispute participants read messages" on public.marketplace_dispute_messages for select to authenticated
using (
  author_id=(select auth.uid())
  or exists(select 1 from public.marketplace_disputes d join public.marketplace_orders o on o.id=d.order_id where d.id=dispute_id and (d.opened_by=(select auth.uid()) or o.client_user_id=(select auth.uid())))
  or public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin','employee','partner'])
);

create or replace function private.assert_member(p_tenant uuid, p_roles text[] default null)
returns void language plpgsql stable security definer set search_path=public,auth as $$
begin
  if (select auth.uid()) is null then raise exception 'authentication_required' using errcode='42501'; end if;
  if not exists(select 1 from public.tenant_memberships m where m.tenant_id=p_tenant and m.user_id=(select auth.uid()) and m.status='active' and (p_roles is null or m.role=any(p_roles))) then
    raise exception 'tenant_access_denied' using errcode='42501';
  end if;
end $$;
revoke all on function private.assert_member(uuid,text[]) from public;
grant execute on function private.assert_member(uuid,text[]) to authenticated;

create or replace function public.toggle_marketplace_favorite(p_tenant uuid,p_listing uuid,p_favorite boolean)
returns boolean language plpgsql security definer set search_path=public,private as $$
begin
  perform private.assert_member(p_tenant,array['client','creator','partner','employee','tenant_admin','super_admin']);
  if not exists(select 1 from public.marketplace_listings l where l.id=p_listing and l.tenant_id=p_tenant and l.status='published') then raise exception 'listing_unavailable' using errcode='22023'; end if;
  if p_favorite then
    insert into public.marketplace_favorites(tenant_id,listing_id,user_id) values(p_tenant,p_listing,(select auth.uid())) on conflict do nothing;
  else
    delete from public.marketplace_favorites where tenant_id=p_tenant and listing_id=p_listing and user_id=(select auth.uid());
  end if;
  return p_favorite;
end $$;

create or replace function public.upsert_marketplace_cart_item(p_tenant uuid,p_listing uuid,p_quantity integer)
returns jsonb language plpgsql security definer set search_path=public,private as $$
declare v_cart uuid; v_price numeric(14,2); v_currency text; v_total numeric(14,2);
begin
  perform private.assert_member(p_tenant,array['client']);
  if p_quantity<1 or p_quantity>100 then raise exception 'invalid_quantity' using errcode='22023'; end if;
  select price_amount,currency into v_price,v_currency from public.marketplace_listings where id=p_listing and tenant_id=p_tenant and status='published' and coalesce((availability->>'available')::boolean,true)=true;
  if not found or v_price is null then raise exception 'listing_unavailable' using errcode='22023'; end if;
  insert into public.marketplace_carts(tenant_id,user_id,status) values(p_tenant,(select auth.uid()),'active') on conflict (tenant_id,user_id,status) do update set updated_at=now() returning id into v_cart;
  insert into public.marketplace_cart_items(cart_id,listing_id,quantity) values(v_cart,p_listing,p_quantity) on conflict (cart_id,listing_id) do update set quantity=excluded.quantity;
  select coalesce(sum(i.quantity*l.price_amount),0) into v_total from public.marketplace_cart_items i join public.marketplace_listings l on l.id=i.listing_id where i.cart_id=v_cart and l.status='published';
  return jsonb_build_object('cartId',v_cart,'currency',v_currency,'total',v_total);
end $$;

create or replace function public.remove_marketplace_cart_item(p_tenant uuid,p_listing uuid)
returns integer language plpgsql security definer set search_path=public,private as $$
declare n integer;
begin
  perform private.assert_member(p_tenant,array['client']);
