  return p_status;
end $$;

create or replace function public.manage_task_runtime(p_tenant uuid,p_task uuid,p_action text,p_payload jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path=public,private as $$
declare v_id uuid; v_status text;
begin
  perform private.assert_member(p_tenant,array['employee','tenant_admin','super_admin']);
  if p_action='create' then
    insert into public.tasks(tenant_id,title,description,status,priority,due_at,created_by) values(p_tenant,left(p_payload->>'title',300),left(p_payload->>'description',5000),'open',coalesce(p_payload->>'priority','normal'),nullif(p_payload->>'dueAt','')::timestamptz,(select auth.uid())) returning id into v_id;
  elsif p_action='update' then
    update public.tasks set title=coalesce(nullif(left(p_payload->>'title',300),''),title),description=coalesce(left(p_payload->>'description',5000),description),priority=coalesce(p_payload->>'priority',priority),due_at=coalesce(nullif(p_payload->>'dueAt','')::timestamptz,due_at),updated_at=now() where id=p_task and tenant_id=p_tenant returning id into v_id;
  elsif p_action='status' then
    select status into v_status from public.tasks where id=p_task and tenant_id=p_tenant for update;
    if not ((v_status='open' and p_payload->>'status' in ('in_progress','cancelled')) or (v_status='in_progress' and p_payload->>'status' in ('blocked','resolved','cancelled')) or (v_status='blocked' and p_payload->>'status' in ('in_progress','cancelled')) or (v_status='resolved' and p_payload->>'status'='closed')) then raise exception 'invalid_task_transition' using errcode='22023'; end if;
    update public.tasks set status=p_payload->>'status',updated_at=now() where id=p_task returning id into v_id;
  else raise exception 'unsupported_task_action' using errcode='22023'; end if;
  if v_id is null then raise exception 'task_not_found' using errcode='22023'; end if;
  insert into public.tenant_admin_audit(tenant_id,actor_id,action,entity_type,entity_id,after_data) values(p_tenant,(select auth.uid()),'task.'||p_action,'task',v_id::text,p_payload);
  return jsonb_build_object('taskId',v_id);
end $$;

create or replace function public.evaluate_sla_runtime(p_tenant uuid,p_policy uuid,p_entity_type text,p_entity_id text,p_started_at timestamptz,p_now timestamptz default now())
returns jsonb language plpgsql security definer set search_path=public,private as $$
declare p public.sla_policies%rowtype; first_deadline timestamptz; resolution_deadline timestamptz; event_name text;
begin
  perform private.assert_member(p_tenant,array['employee','tenant_admin','super_admin']);
  select * into p from public.sla_policies where id=p_policy and tenant_id=p_tenant and active=true;
  if p.id is null then raise exception 'sla_policy_not_found' using errcode='22023'; end if;
  first_deadline=p_started_at+make_interval(mins=>p.first_response_minutes); resolution_deadline=p_started_at+make_interval(mins=>p.resolution_minutes);
  event_name=case when p_now>=resolution_deadline then 'breached' when p_now>=resolution_deadline-make_interval(mins=>greatest(1,p.resolution_minutes/10)) then 'warning' else 'started' end;
  insert into public.sla_events(tenant_id,policy_id,entity_type,entity_id,event_type,deadline_at,idempotency_key) values(p_tenant,p_policy,p_entity_type,p_entity_id,event_name,resolution_deadline,p_entity_type||':'||p_entity_id||':'||event_name) on conflict do nothing;
  return jsonb_build_object('event',event_name,'firstResponseDeadline',first_deadline,'resolutionDeadline',resolution_deadline);
end $$;

create or replace function public.start_workflow_runtime(p_tenant uuid,p_workflow uuid,p_idempotency_key text,p_context jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path=public,private as $$
declare v_run uuid; v_existing boolean:=false;
begin
  perform private.assert_member(p_tenant,array['employee','tenant_admin','super_admin']);
  if p_idempotency_key !~ '^[A-Za-z0-9_-]{12,100}$' then raise exception 'invalid_idempotency_key' using errcode='22023'; end if;
  select id into v_run from public.workflow_runs where tenant_id=p_tenant and idempotency_key=p_idempotency_key;
  if v_run is not null then v_existing=true; else
    if not exists(select 1 from public.workflow_definitions where id=p_workflow and tenant_id=p_tenant and status='published') then raise exception 'workflow_not_published' using errcode='22023'; end if;
    insert into public.workflow_runs(tenant_id,workflow_id,idempotency_key,status,context,started_at) values(p_tenant,p_workflow,p_idempotency_key,'running',p_context,now()) returning id into v_run;
    insert into public.workflow_events(tenant_id,run_id,event_type,idempotency_key,payload) values(p_tenant,v_run,'started',p_idempotency_key||':started',p_context);
  end if;
  return jsonb_build_object('runId',v_run,'duplicate',v_existing);
end $$;

create or replace function public.advance_workflow_runtime(p_tenant uuid,p_run uuid,p_success boolean,p_error_code text default null)
returns text language plpgsql security definer set search_path=public,private as $$
declare r public.workflow_runs%rowtype; v_steps integer;
begin
  perform private.assert_member(p_tenant,array['employee','tenant_admin','super_admin']);
  select * into r from public.workflow_runs where id=p_run and tenant_id=p_tenant for update;
  if r.id is null or r.status not in ('running','failed','waiting') then raise exception 'workflow_run_not_advanceable' using errcode='22023'; end if;
  select count(*) into v_steps from public.workflow_steps where workflow_id=r.workflow_id;
  if p_success then
    update public.workflow_runs set current_step=current_step+1,status=case when current_step+1>=v_steps then 'completed' else 'running' end,finished_at=case when current_step+1>=v_steps then now() else null end,last_error_code=null where id=p_run returning status into r.status;
  else
    update public.workflow_runs set retry_count=retry_count+1,status=case when retry_count+1>=3 then 'failed' else 'waiting' end,last_error_code=left(p_error_code,120) where id=p_run returning status into r.status;
  end if;
  insert into public.workflow_events(tenant_id,run_id,event_type,idempotency_key,error_code) values(p_tenant,p_run,case when p_success then case when r.status='completed' then 'completed' else 'started' end else case when r.status='failed' then 'failed' else 'retried' end end,gen_random_uuid()::text,left(p_error_code,120));
  return r.status;
end $$;

