create or replace function public.open_marketplace_dispute(p_tenant uuid,p_order uuid,p_reason text)
returns uuid language plpgsql security definer set search_path=public,private as $$
declare v_id uuid;
begin
  perform private.assert_member(p_tenant,array['client']);
  if not exists(select 1 from public.marketplace_orders where id=p_order and tenant_id=p_tenant and client_user_id=(select auth.uid()) and status in ('confirmed','in_progress','completed')) then raise exception 'dispute_not_allowed' using errcode='42501'; end if;
  if exists(select 1 from public.marketplace_disputes where order_id=p_order and status in ('open','under_review')) then raise exception 'duplicate_dispute' using errcode='23505'; end if;
  insert into public.marketplace_disputes(tenant_id,order_id,opened_by,reason,status) values(p_tenant,p_order,(select auth.uid()),left(p_reason,3000),'open') returning id into v_id;
  return v_id;
end $$;

create or replace function public.add_marketplace_dispute_message(p_tenant uuid,p_dispute uuid,p_body text)
returns uuid language plpgsql security definer set search_path=public,private as $$
declare v_id uuid;
begin
  perform private.assert_member(p_tenant,null);
  if not exists(select 1 from public.marketplace_disputes d join public.marketplace_orders o on o.id=d.order_id where d.id=p_dispute and d.tenant_id=p_tenant and d.status in ('open','under_review') and (d.opened_by=(select auth.uid()) or o.client_user_id=(select auth.uid()) or public.current_user_has_tenant_role(p_tenant,array['partner','employee','tenant_admin','super_admin']))) then raise exception 'dispute_message_denied' using errcode='42501'; end if;
  insert into public.marketplace_dispute_messages(tenant_id,dispute_id,author_id,body) values(p_tenant,p_dispute,(select auth.uid()),left(p_body,5000)) returning id into v_id;
  return v_id;
end $$;

