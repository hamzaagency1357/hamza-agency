create or replace function public.checkout_marketplace_cart(p_tenant uuid,p_idempotency_key text)
returns jsonb language plpgsql security definer set search_path=public,private as $$
declare v_cart uuid; v_order uuid; v_code text; v_currency text; v_total numeric(14,2);
begin
  perform private.assert_member(p_tenant,array['client']);
  if p_idempotency_key !~ '^[A-Za-z0-9_-]{12,100}$' then raise exception 'invalid_idempotency_key' using errcode='22023'; end if;
  select order_id into v_order from public.commerce_events where tenant_id=p_tenant and idempotency_key='checkout:'||p_idempotency_key;
  if v_order is not null then return (select jsonb_build_object('orderId',id,'orderCode',order_code,'duplicate',true) from public.marketplace_orders where id=v_order); end if;
  select id into v_cart from public.marketplace_carts where tenant_id=p_tenant and user_id=(select auth.uid()) and status='active' for update;
  if v_cart is null or not exists(select 1 from public.marketplace_cart_items where cart_id=v_cart) then raise exception 'empty_cart' using errcode='22023'; end if;
  if exists(select 1 from public.marketplace_cart_items i left join public.marketplace_listings l on l.id=i.listing_id where i.cart_id=v_cart and (l.id is null or l.status<>'published' or l.price_amount is null or coalesce((l.availability->>'available')::boolean,true)=false)) then raise exception 'cart_contains_unavailable_listing' using errcode='22023'; end if;
  select min(currency),sum(i.quantity*l.price_amount) into v_currency,v_total from public.marketplace_cart_items i join public.marketplace_listings l on l.id=i.listing_id where i.cart_id=v_cart;
  if exists(select 1 from public.marketplace_cart_items i join public.marketplace_listings l on l.id=i.listing_id where i.cart_id=v_cart and l.currency is distinct from v_currency) then raise exception 'mixed_currency_cart' using errcode='22023'; end if;
  v_code='ORD-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,12));
  insert into public.marketplace_orders(tenant_id,order_code,client_user_id,status,currency,subtotal,total,payment_status) values(p_tenant,v_code,(select auth.uid()),'pending',v_currency,v_total,v_total,'unpaid') returning id into v_order;
  insert into public.marketplace_order_items(order_id,tenant_id,listing_id,title_snapshot,quantity,unit_price,total_price)
  select v_order,p_tenant,l.id,coalesce(l.translations,'{}'::jsonb),i.quantity,l.price_amount,i.quantity*l.price_amount from public.marketplace_cart_items i join public.marketplace_listings l on l.id=i.listing_id where i.cart_id=v_cart;
  update public.marketplace_carts set status='converted',updated_at=now() where id=v_cart;
  insert into public.commerce_events(tenant_id,order_id,actor_id,event_type,idempotency_key,payload) values(p_tenant,v_order,(select auth.uid()),'order.created','checkout:'||p_idempotency_key,jsonb_build_object('total',v_total));
  return jsonb_build_object('orderId',v_order,'orderCode',v_code,'duplicate',false,'total',v_total);
end $$;

create or replace function public.transition_marketplace_order(p_tenant uuid,p_order uuid,p_status text)
returns text language plpgsql security definer set search_path=public,private as $$
declare v_old text; v_client uuid;
begin
  perform private.assert_member(p_tenant,array['partner','employee','tenant_admin','super_admin','client']);
  select status,client_user_id into v_old,v_client from public.marketplace_orders where id=p_order and tenant_id=p_tenant for update;
  if not found then raise exception 'order_not_found' using errcode='22023'; end if;
  if v_client=(select auth.uid()) then
    if not (v_old='pending' and p_status='cancelled') then raise exception 'client_transition_denied' using errcode='42501'; end if;
  elsif not public.current_user_has_tenant_role(p_tenant,array['partner','employee','tenant_admin','super_admin']) then raise exception 'order_transition_denied' using errcode='42501'; end if;
  if not ((v_old='pending' and p_status in ('confirmed','cancelled')) or (v_old='confirmed' and p_status in ('in_progress','cancelled')) or (v_old='in_progress' and p_status in ('completed','cancelled'))) then raise exception 'invalid_order_transition' using errcode='22023'; end if;
  update public.marketplace_orders set status=p_status,updated_at=now() where id=p_order;
  insert into public.commerce_events(tenant_id,order_id,actor_id,event_type,payload) values(p_tenant,p_order,(select auth.uid()),'order.status_changed',jsonb_build_object('from',v_old,'to',p_status));
  return p_status;
end $$;

create or replace function public.create_marketplace_review(p_tenant uuid,p_order uuid,p_listing uuid,p_rating integer,p_body text default null)
returns uuid language plpgsql security definer set search_path=public,private as $$
declare v_id uuid;
begin
  perform private.assert_member(p_tenant,array['client']);
  if p_rating not between 1 and 5 then raise exception 'invalid_rating' using errcode='22023'; end if;
  if not exists(select 1 from public.marketplace_orders o join public.marketplace_order_items i on i.order_id=o.id where o.id=p_order and o.tenant_id=p_tenant and o.client_user_id=(select auth.uid()) and o.status='completed' and i.listing_id=p_listing) then raise exception 'review_not_allowed' using errcode='42501'; end if;
  insert into public.marketplace_reviews(tenant_id,listing_id,order_id,user_id,rating,body,status) values(p_tenant,p_listing,p_order,(select auth.uid()),p_rating,left(p_body,3000),'pending') returning id into v_id;
  return v_id;
exception when unique_violation then raise exception 'duplicate_review' using errcode='23505';
end $$;

create or replace function public.request_marketplace_refund(p_tenant uuid,p_order uuid,p_amount numeric,p_reason text)
returns uuid language plpgsql security definer set search_path=public,private as $$
