returns jsonb language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_guard jsonb;v_id bigint;v_question text;
begin
  v_guard:=public.pr99_guard_submission('ai_support',p_identity,p_payload,p_started_at,p_honeypot);
  if not coalesce((v_guard->>'allowed')::boolean,false) then return v_guard; end if;
