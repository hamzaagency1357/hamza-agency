  if length(v_question)<2 then return jsonb_build_object('allowed',false,'code','invalid_request');end if;
  insert into public.ai_unanswered_questions(question,page_url,visitor_info,status,answer,internal_notes,context,source,visitor_name,visitor_whatsapp,metadata)
  values(v_question,nullif(public.pr99_sanitize_text(p_payload->>'page_url',2000),''),jsonb_build_object('email_hash',nullif(p_payload->>'email_hash',''),'phone_hash',nullif(p_payload->>'phone_hash','')),'new',null,null,nullif(public.pr99_sanitize_text(p_payload->>'context',2000),''),'public_ai_support',nullif(public.pr99_sanitize_text(p_payload->>'visitor_name',160),''),nullif(public.pr99_sanitize_text(p_payload->>'visitor_whatsapp',40),''),'{}'::jsonb) returning id into v_id;
  return jsonb_build_object('allowed',true,'code','ok','id',v_id);
end $$;

