create or replace function public.pr99_guard_submission(
  p_form_type text,
  p_identity text,
  p_payload jsonb,
  p_started_at timestamptz,
  p_honeypot text default ''
) returns jsonb
language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_identity_hash text;
  v_payload_hash text;
  v_recent integer;
  v_hourly integer;
  v_duplicate integer;
  v_reason text;
begin
  if p_form_type not in ('application','service_request','job_application','contact','ai_support','password_reset') then
    raise exception 'Invalid form type';
  end if;
  if length(coalesce(p_payload::text,'')) > 30000 then
    v_reason := 'payload_too_large';
  elsif coalesce(trim(p_honeypot),'') <> '' then
    v_reason := 'honeypot';
  elsif p_started_at is null or p_started_at > now() + interval '30 seconds' or now() - p_started_at < interval '2 seconds' then
    v_reason := 'submitted_too_fast';
  end if;

  v_identity_hash := encode(digest(convert_to(lower(trim(coalesce(p_identity,''))) || ':' || p_form_type,'UTF8'),'sha256'),'hex');
  v_payload_hash := encode(digest(convert_to(coalesce(p_payload,'{}'::jsonb)::text,'UTF8'),'sha256'),'hex');

  select count(*) into v_recent from public.public_submission_guards
   where form_type=p_form_type and identity_hash=v_identity_hash and accepted=true and created_at>now()-interval '15 minutes';
  select count(*) into v_hourly from public.public_submission_guards
   where form_type=p_form_type and identity_hash=v_identity_hash and created_at>now()-interval '1 hour';
  select count(*) into v_duplicate from public.public_submission_guards
   where form_type=p_form_type and payload_hash=v_payload_hash and accepted=true and created_at>now()-interval '24 hours';

  if v_reason is null and (v_recent >= 3 or v_hourly >= 8) then v_reason := 'cooldown'; end if;
  if v_reason is null and v_duplicate >= 1 then v_reason := 'duplicate'; end if;

  insert into public.public_submission_guards(form_type,identity_hash,payload_hash,accepted,reason)
  values(p_form_type,v_identity_hash,v_payload_hash,v_reason is null,v_reason);

  return jsonb_build_object('allowed',v_reason is null,'code',case when v_reason is null then 'ok' else 'try_again_later' end);
end $$;
revoke all on function public.pr99_guard_submission(text,text,jsonb,timestamptz,text) from public;
grant execute on function public.pr99_guard_submission(text,text,jsonb,timestamptz,text) to anon,authenticated;

create or replace function public.pr99_submit_application(p_payload jsonb,p_identity text,p_started_at timestamptz,p_honeypot text default '')
returns jsonb language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_guard jsonb;v_id bigint;v_name text;v_country text;v_phone text;v_platform text;
begin
  v_guard:=public.pr99_guard_submission('application',p_identity,p_payload,p_started_at,p_honeypot);
  if not coalesce((v_guard->>'allowed')::boolean,false) then return v_guard; end if;
  v_name:=trim(public.pr99_sanitize_text(p_payload->>'full_name',160));v_country:=trim(public.pr99_sanitize_text(p_payload->>'country',120));
  v_phone:=trim(public.pr99_sanitize_text(p_payload->>'whatsapp',40));v_platform:=trim(public.pr99_sanitize_text(p_payload->>'platform',120));
  if length(v_name)<2 or length(v_country)<2 or length(regexp_replace(v_phone,'[^0-9]','','g'))<8 or length(v_platform)<2 then return jsonb_build_object('allowed',false,'code','invalid_request');end if;
  insert into public.agency_applications(full_name,country,whatsapp,platform,previous_experience,notes,status,internal_notes)
  values(v_name,v_country,v_phone,v_platform,nullif(public.pr99_sanitize_text(p_payload->>'previous_experience',4000),''),nullif(public.pr99_sanitize_text(p_payload->>'notes',4000),''),'new',null)
  returning id into v_id;
  return jsonb_build_object('allowed',true,'code','ok','id',v_id);
end $$;

create or replace function public.pr99_submit_service_request(p_payload jsonb,p_identity text,p_started_at timestamptz,p_honeypot text default '')
returns jsonb language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_guard jsonb;v_id bigint;v_code text;v_name text;v_phone text;v_type text;
begin
  v_guard:=public.pr99_guard_submission('service_request',p_identity,p_payload,p_started_at,p_honeypot);
  if not coalesce((v_guard->>'allowed')::boolean,false) then return v_guard; end if;
  v_name:=trim(public.pr99_sanitize_text(p_payload->>'full_name',160));v_phone:=trim(public.pr99_sanitize_text(p_payload->>'whatsapp',40));v_type:=trim(public.pr99_sanitize_text(p_payload->>'service_type',120));
  if length(v_name)<2 or length(regexp_replace(v_phone,'[^0-9]','','g'))<8 or length(v_type)<2 then return jsonb_build_object('allowed',false,'code','invalid_request');end if;
  v_code:='SR-'||to_char(now(),'YYYY')||'-'||upper(substr(encode(gen_random_bytes(8),'hex'),1,10));
  insert into public.service_requests(request_code,full_name,country,whatsapp,service_type,platform,account_identifier,requested_amount,notes,status,internal_notes)
  values(v_code,v_name,nullif(public.pr99_sanitize_text(p_payload->>'country',120),''),v_phone,v_type,nullif(public.pr99_sanitize_text(p_payload->>'platform',120),''),nullif(public.pr99_sanitize_text(p_payload->>'account_identifier',240),''),nullif(public.pr99_sanitize_text(p_payload->>'requested_amount',120),''),nullif(public.pr99_sanitize_text(p_payload->>'notes',4000),''),'new',null)
  returning id into v_id;
  return jsonb_build_object('allowed',true,'code','ok','id',v_id,'tracking_code',v_code);
end $$;

create or replace function public.pr99_submit_job_application(p_payload jsonb,p_identity text,p_started_at timestamptz,p_honeypot text default '')
returns jsonb language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_guard jsonb;v_id bigint;v_name text;v_phone text;v_job bigint;
begin
  v_guard:=public.pr99_guard_submission('job_application',p_identity,p_payload,p_started_at,p_honeypot);
  if not coalesce((v_guard->>'allowed')::boolean,false) then return v_guard; end if;
  v_name:=trim(public.pr99_sanitize_text(p_payload->>'full_name',160));v_phone:=trim(public.pr99_sanitize_text(p_payload->>'whatsapp',40));
  begin v_job:=nullif(p_payload->>'job_id','')::bigint; exception when others then v_job:=null; end;
  if length(v_name)<2 or length(regexp_replace(v_phone,'[^0-9]','','g'))<8 then return jsonb_build_object('allowed',false,'code','invalid_request');end if;
  insert into public.job_applications(job_id,full_name,country,whatsapp,email,experience,answers,notes,status,internal_notes)
  values(v_job,v_name,nullif(public.pr99_sanitize_text(p_payload->>'country',120),''),v_phone,nullif(lower(public.pr99_sanitize_text(p_payload->>'email',254)),''),nullif(public.pr99_sanitize_text(p_payload->>'experience',5000),''),case when jsonb_typeof(p_payload->'answers')='object' then p_payload->'answers' else '{}'::jsonb end,nullif(public.pr99_sanitize_text(p_payload->>'notes',4000),''),'new',null)
  returning id into v_id;
  return jsonb_build_object('allowed',true,'code','ok','id',v_id);
end $$;

