  select * into v_suggestion from public.pr4_knowledge_suggestions where id=p_suggestion_id;
  if not found then raise exception 'suggestion not found'; end if;
  insert into public.pr4_knowledge_base(question,answer,language,category,source_type,status,created_by,updated_by)
  values(v_suggestion.question_redacted,'',v_suggestion.language,'suggested','suggested','draft',v_actor,v_actor) returning id into v_id;
  update public.pr4_knowledge_suggestions set status='drafted',updated_at=now() where id=p_suggestion_id;
  return v_id;
end $$;

