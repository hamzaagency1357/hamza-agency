create or replace function public.pr4_support_action(p_request_id bigint,p_action text,p_value text default null,p_note text default null)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_admin bigint:=public.pr4_current_admin_id();v_old public.pr4_support_requests%rowtype;v_new_status text;v_assignee bigint;
begin
  if v_admin is null or not public.pr4_admin_can_module('ai_support','can_edit') then raise exception 'forbidden'; end if;
  select * into v_old from public.pr4_support_requests where id=p_request_id for update;
  if not found then raise exception 'support request not found'; end if;
  if p_action='accept' then
    update public.pr4_support_requests set assigned_admin_id=coalesce(assigned_admin_id,v_admin),status='accepted',accepted_at=coalesce(accepted_at,now()),updated_at=now() where id=p_request_id;
    v_new_status:='accepted';
  elsif p_action='assign' then
    if not public.pr4_admin_can_module('ai_support','can_manage') then raise exception 'forbidden'; end if;
    select id::bigint into v_assignee from public.admin_users where is_active is not false and lower(email)=lower(trim(coalesce(p_value,''))) limit 1;
    if v_assignee is null then raise exception 'staff not found'; end if;
    update public.pr4_support_requests set assigned_admin_id=v_assignee,updated_at=now() where id=p_request_id;
  elsif p_action='priority' then
    if p_value not in('low','normal','high','urgent') then raise exception 'invalid priority'; end if;
    update public.pr4_support_requests set priority=p_value,updated_at=now() where id=p_request_id;
  elsif p_action='status' then
    if p_value not in('new','awaiting_acceptance','accepted','responding','awaiting_user','resolved','closed','cancelled') then raise exception 'invalid status'; end if;
    if p_value in('closed','cancelled') and length(trim(coalesce(p_note,'')))<3 then raise exception 'close reason required'; end if;
    update public.pr4_support_requests set status=p_value,close_reason=case when p_value in('closed','cancelled') then left(trim(p_note),500) else close_reason end,resolved_at=case when p_value='resolved' then coalesce(resolved_at,now()) else resolved_at end,closed_at=case when p_value in('closed','cancelled') then now() else closed_at end,updated_at=now() where id=p_request_id;
    v_new_status:=p_value;
  elsif p_action='reply' then
    if length(trim(coalesce(p_value,'')))<1 then raise exception 'reply required'; end if;
    insert into public.pr4_support_messages(request_id,role,body,public_visible,actor_admin_id) values(p_request_id,'staff',left(trim(p_value),8000),true,v_admin);
    update public.pr4_support_requests set last_response=left(trim(p_value),2000),status=case when status in('resolved','closed','cancelled') then status else 'awaiting_user' end,updated_at=now() where id=p_request_id;
    v_new_status:='awaiting_user';
  elsif p_action='note' then
    if length(trim(coalesce(p_value,'')))<1 then raise exception 'note required'; end if;
    insert into public.pr4_support_internal_notes(request_id,note,actor_admin_id) values(p_request_id,left(trim(p_value),8000),v_admin);
  else
    raise exception 'unsupported action';
  end if;
  insert into public.pr4_support_history(request_id,action,from_status,to_status,actor_admin_id,metadata) values(p_request_id,p_action,v_old.status,v_new_status,v_admin,jsonb_build_object('value',case when p_action in('reply','note') then null else left(coalesce(p_value,''),300) end,'note',case when p_action='status' then left(coalesce(p_note,''),500) else null end));
  return jsonb_build_object('ok',true,'requestId',p_request_id,'action',p_action);
end $$;

create or replace view public.pr4_notification_inbox with (security_invoker=true) as
select n.*,
  coalesce(n.resource_module,case
    when n.entity_type in('agency_applications','applications') then 'applications'
    when n.entity_type='service_requests' then 'service_requests'
    when n.entity_type in('job_applications','jobs') then 'jobs'
    when n.entity_type in('contact_messages','contact_requests') then 'contact'
    when n.entity_type='pr4_support_requests' then 'ai_support'
    else 'notifications' end) as effective_resource_module
from public.notifications n
where coalesce(n.is_deleted,false)=false
  and public.pr4_admin_can_module(coalesce(n.resource_module,case
    when n.entity_type in('agency_applications','applications') then 'applications'
    when n.entity_type='service_requests' then 'service_requests'
    when n.entity_type in('job_applications','jobs') then 'jobs'
    when n.entity_type in('contact_messages','contact_requests') then 'contact'
    when n.entity_type='pr4_support_requests' then 'ai_support'
    else 'notifications' end),'can_view');

grant select on public.pr4_notification_inbox to authenticated;

create or replace function public.pr4_notification_action(p_ids bigint[],p_action text)
returns integer language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_count integer;
begin
  if not public.pr4_admin_can_module('notifications','can_edit') then raise exception 'forbidden'; end if;
  if p_action='read' then update public.notifications set is_read=true,workflow_status=case when workflow_status='new' then 'viewed' else workflow_status end where id=any(p_ids) and id in(select id from public.pr4_notification_inbox); get diagnostics v_count=row_count;
  elsif p_action='read_all' then update public.notifications set is_read=true,workflow_status=case when workflow_status='new' then 'viewed' else workflow_status end where id in(select id from public.pr4_notification_inbox); get diagnostics v_count=row_count;
  elsif p_action in('new','viewed','in_progress','actioned','archived') then update public.notifications set workflow_status=p_action,is_archived=(p_action='archived') where id=any(p_ids) and id in(select id from public.pr4_notification_inbox); get diagnostics v_count=row_count;
  else raise exception 'unsupported notification action'; end if;
  return coalesce(v_count,0);
end $$;

