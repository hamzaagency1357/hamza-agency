create or replace function public.pr4_save_knowledge(
  p_id bigint,p_question text,p_answer text,p_alternatives text[],p_keywords text[],p_language text,p_program_slug text,p_service_slug text,p_page_path text,p_category text,p_source_type text,p_source_label text,p_source_url text,p_priority integer,p_start_at timestamptz,p_expires_at timestamptz,p_status text
) returns public.pr4_knowledge_base language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_actor text:=lower(coalesce(auth.jwt()->>'email',''));v_row public.pr4_knowledge_base%rowtype;v_status text:=coalesce(p_status,'draft');
begin
  if not public.pr4_admin_can_module('knowledge_base',case when p_id is null then 'can_create' else 'can_edit' end) then raise exception 'forbidden'; end if;
  if p_language not in('ar','en','tr') or v_status not in('draft','review','published','disabled','archived') then raise exception 'invalid knowledge state'; end if;
  if trim(coalesce(p_question,''))='' or trim(coalesce(p_answer,''))='' then raise exception 'question and answer are required'; end if;
  if p_id is null then
    insert into public.pr4_knowledge_base(question,answer,alternatives,keywords,language,program_slug,service_slug,page_path,category,source_type,source_label,source_url,priority,start_at,expires_at,status,created_by,updated_by,published_by,published_at)
    values(left(trim(p_question),1500),left(trim(p_answer),12000),coalesce(p_alternatives,'{}'),coalesce(p_keywords,'{}'),p_language,nullif(trim(p_program_slug),''),nullif(trim(p_service_slug),''),nullif(trim(p_page_path),''),left(coalesce(nullif(trim(p_category),''),'general'),100),case when p_source_type in('admin','suggested','published_page','program','service','faq','blog','job','policy','contact','hours','tracking') then p_source_type else 'admin' end,nullif(left(trim(p_source_label),300),''),nullif(left(trim(p_source_url),1200),''),greatest(-100,least(100,coalesce(p_priority,0))),p_start_at,p_expires_at,v_status,v_actor,v_actor,case when v_status='published' then v_actor end,case when v_status='published' then now() end)
    returning * into v_row;
  else
    update public.pr4_knowledge_base set question=left(trim(p_question),1500),answer=left(trim(p_answer),12000),alternatives=coalesce(p_alternatives,'{}'),keywords=coalesce(p_keywords,'{}'),language=p_language,program_slug=nullif(trim(p_program_slug),''),service_slug=nullif(trim(p_service_slug),''),page_path=nullif(trim(p_page_path),''),category=left(coalesce(nullif(trim(p_category),''),'general'),100),source_type=case when p_source_type in('admin','suggested','published_page','program','service','faq','blog','job','policy','contact','hours','tracking') then p_source_type else 'admin' end,source_label=nullif(left(trim(p_source_label),300),''),source_url=nullif(left(trim(p_source_url),1200),''),priority=greatest(-100,least(100,coalesce(p_priority,0))),start_at=p_start_at,expires_at=p_expires_at,status=v_status,updated_by=v_actor,published_by=case when v_status='published' and status<>'published' then v_actor else published_by end,published_at=case when v_status='published' and status<>'published' then now() when v_status<>'published' then null else published_at end where id=p_id returning * into v_row;
    if not found then raise exception 'knowledge not found'; end if;
  end if;
  return v_row;
end $$;

create or replace function public.pr4_suggest_knowledge(p_question text,p_language text)
returns void language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_question text;
begin
  if p_language not in('ar','en','tr') then return; end if;
  v_question:=left(trim(coalesce(p_question,'')),800);
  v_question:=regexp_replace(v_question,'[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}','[email]','gi');
  v_question:=regexp_replace(v_question,'\+?[0-9][0-9 ()-]{7,}[0-9]','[phone]','g');
  v_question:=regexp_replace(v_question,'https?://\S+','[link]','gi');
  if length(v_question)<4 then return; end if;
  insert into public.pr4_knowledge_suggestions(question_redacted,language) values(v_question,p_language)
  on conflict(question_redacted,language) do update set occurrences=public.pr4_knowledge_suggestions.occurrences+1,updated_at=now();
end $$;

create or replace function public.pr4_promote_suggestion(p_suggestion_id bigint)
returns bigint language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_actor text:=lower(coalesce(auth.jwt()->>'email',''));v_suggestion public.pr4_knowledge_suggestions%rowtype;v_id bigint;
begin
