create or replace function public.pr4_current_admin_id()
returns bigint language sql stable security definer set search_path=pg_catalog,public as $$
  select au.id::bigint
  from public.admin_users au
  where au.is_active is not false
    and (au.user_id = auth.uid() or (au.user_id is null and lower(au.email)=lower(coalesce(auth.jwt()->>'email',''))))
  order by case when au.user_id=auth.uid() then 0 else 1 end
  limit 1
$$;

create or replace function public.pr4_admin_can_module(p_module text, p_action text default 'can_view')
returns boolean language plpgsql stable security definer set search_path=pg_catalog,public as $$
declare
  v_admin public.admin_users%rowtype;
  v_value boolean := false;
begin
  select * into v_admin from public.admin_users where id=public.pr4_current_admin_id() and is_active is not false;
  if not found then return false; end if;
  if v_admin.role='super_admin' then return true; end if;
  if v_admin.role='program_admin' and p_module not in ('dashboard','applications','programs') then return false; end if;
  select case p_action
    when 'can_create' then coalesce(ap.can_create,false)
    when 'can_edit' then coalesce(ap.can_edit,false)
    when 'can_delete' then coalesce(ap.can_delete,false)
    when 'can_export' then coalesce(ap.can_export,false)
    when 'can_manage' then coalesce(ap.can_manage,false)
    else coalesce(ap.can_view,false)
  end or coalesce(ap.can_manage,false)
  into v_value
  from public.admin_permissions ap
  where ap.module_key=p_module
    and (ap.admin_user_id=v_admin.id or (ap.admin_user_id is null and lower(ap.admin_email)=lower(v_admin.email)))
  order by case when ap.admin_user_id=v_admin.id then 0 else 1 end
  limit 1;
  if v_admin.role='deputy_super_admin' and v_value is null then return true; end if;
  return coalesce(v_value, v_admin.role='deputy_super_admin');
end $$;

