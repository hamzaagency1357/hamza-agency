create policy "members read own tenant" on public.tenants for select to authenticated using (public.current_user_has_tenant_role(id,array['super_admin','tenant_admin','creator','client','employee','partner']));
create policy "tenant domains select" on public.tenant_domains for select to authenticated using (public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin','employee','partner']));
create policy "users read own memberships" on public.tenant_memberships for select to authenticated using (auth.uid()=user_id or public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin']));
create policy "tenant admins create memberships" on public.tenant_memberships for insert to authenticated with check (private.can_manage_tenant_member(tenant_id,role));
create policy "tenant admins update memberships" on public.tenant_memberships for update to authenticated using (private.can_manage_tenant_member(tenant_id,role)) with check (private.can_manage_tenant_member(tenant_id,role));
create policy "tenant admins read tenant audit" on public.tenant_admin_audit for select to authenticated using (public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin']));
create policy "tenant admins write tenant audit" on public.tenant_admin_audit for insert to authenticated with check (actor_id=auth.uid() and public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin']));
create policy "users read own sessions" on public.user_sessions for select to authenticated using (user_id=auth.uid());
create policy "users register own sessions" on public.user_sessions for insert to authenticated with check (user_id=auth.uid() and public.current_user_has_tenant_role(tenant_id,array['super_admin','tenant_admin','creator','client','employee','partner']));
create policy "users revoke own sessions" on public.user_sessions for update to authenticated using (user_id=auth.uid()) with check (user_id=auth.uid());

revoke all on all tables in schema public from anon;
grant select on public.tenants,public.tenant_domains,public.programs,public.tenant_memberships,public.tenant_admin_audit,public.notifications,public.user_sessions,public.tenant_branding,public.tenant_feature_flags,public.tenant_settings to authenticated;
grant insert,update on public.tenant_memberships to authenticated;
grant insert on public.tenant_admin_audit,public.notifications,public.user_sessions to authenticated;
grant update on public.user_sessions to authenticated;
grant usage,select on all sequences in schema public to authenticated,service_role;
grant all on all tables in schema public to service_role;
